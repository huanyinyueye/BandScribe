// Generates internal/export/gp/tables_gen.go from the installed alphaTab, so the Go GP writer
// uses alphaTab's exact static data (program sounds, drum kit, tuning presets, stylesheet).
//
// Usage (in exporter/): node gen_gp_tables.mjs ../internal/export/gp/tables_gen.go
import fs from 'node:fs';
import zlib from 'node:zlib';
import * as alphaTab from '@coderline/alphatab';

const m = alphaTab.model;
const settings = new alphaTab.Settings();

function unzip(data) {
  const out = new Map();
  let p = 0;
  const dv = new DataView(data.buffer, data.byteOffset, data.byteLength);
  while (dv.getUint32(p, true) === 0x04034b50) {
    const method = dv.getUint16(p + 8, true);
    const csize = dv.getUint32(p + 18, true);
    const nlen = dv.getUint16(p + 26, true);
    const xlen = dv.getUint16(p + 28, true);
    const name = Buffer.from(data.subarray(p + 30, p + 30 + nlen)).toString('utf-8');
    const start = p + 30 + nlen + xlen;
    const raw = data.subarray(start, start + csize);
    out.set(name, method === 8 ? zlib.inflateRawSync(raw) : Buffer.from(raw));
    p = start + csize;
  }
  return out;
}

const score = new m.Score();
const mb = new m.MasterBar();
score.addMasterBar(mb);
for (let program = 0; program <= 128; program++) {
  const track = new m.Track();
  track.name = `t${program}`;
  track.ensureStaveCount(1);
  const staff = track.staves[0];
  if (program === 128) {
    staff.isPercussion = true;
    track.playbackInfo.primaryChannel = 9;
    track.playbackInfo.secondaryChannel = 9;
  } else {
    track.playbackInfo.program = program;
    track.playbackInfo.primaryChannel = 0;
    track.playbackInfo.secondaryChannel = 1;
  }
  score.addTrack(track);
  const bar = new m.Bar();
  staff.addBar(bar);
  const voice = new m.Voice();
  bar.addVoice(voice);
  voice.addBeat(new m.Beat());
}
score.finish(settings);
const files = unzip(new alphaTab.exporter.Gp7Exporter().export(score, settings));
const gpif = files.get('Content/score.gpif').toString('utf-8');

const tracks = [...gpif.matchAll(/<Track id="(\d+)">(.*?)<\/Track>/gs)].map((x) => x[2]);
const tag = (s, name) => {
  const r = new RegExp(`<${name}>(.*?)</${name}>`, 's').exec(s);
  if (!r) throw new Error(`missing ${name}`);
  return r[1];
};
const unescape = (s) => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
  .replace(/&apos;/g, "'").replace(/&amp;/g, '&');
const q = (s) => JSON.stringify(unescape(s));

const lines = [];
lines.push('// Code generated by exporter/gen_gp_tables.mjs from alphaTab ' + alphaTab.meta.version + '; DO NOT EDIT.');
lines.push('//');
lines.push('// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy');
lines.push('// of the MPL was not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.');
lines.push('// The data is taken from alphaTab (https://github.com/CoderLine/alphaTab), Copyright CoderLine.');
lines.push('');
lines.push('package gp');
lines.push('');
lines.push(`const alphaTabVersion = ${JSON.stringify(alphaTab.meta.version)}`);
lines.push(`const alphaTabComment = ${JSON.stringify(/<!-- (.*?) -->/.exec(gpif)[1])}`);
lines.push('');
lines.push('// programInfo is GpifSoundMapper._midiProgramInfoLookup: icon id, instrument set name and type.');
lines.push('var programInfo = [128]struct {');
lines.push('\ticon       int');
lines.push('\tname, kind string');
lines.push('}{');
for (let program = 0; program < 128; program++) {
  const t = tracks[program];
  const set = tag(t, 'InstrumentSet');
  lines.push(`\t{${tag(t, 'IconId')}, ${q(tag(set, 'Name'))}, ${q(tag(set, 'Type'))}},`);
}
lines.push('}');
lines.push('');
const drum = tag(tracks[128], 'InstrumentSet');
lines.push('// drumKit is GpifSoundMapper._buildPercussionInstrumentSet for the default articulations.');
lines.push('var drumKit = []drumElement{');
for (const el of drum.matchAll(/<Element>(.*?)<\/Element>/gs)) {
  const e = el[1];
  lines.push(`\t{${q(tag(e, 'Name'))}, ${q(tag(e, 'Type'))}, ${q(tag(e, 'SoundbankName'))}, []drumArticulation{`);
  for (const ar of e.matchAll(/<Articulation>(.*?)<\/Articulation>/gs)) {
    const a = ar[1];
    lines.push(`\t\t{${q(tag(a, 'Name'))}, ${tag(a, 'StaffLine')}, ${q(tag(a, 'Noteheads'))}, ${q(tag(a, 'TechniquePlacement'))}, ` +
      `${q(tag(a, 'TechniqueSymbol'))}, ${q(tag(a, 'InputMidiNumbers'))}, ${q(tag(a, 'OutputRSESound'))}, ${tag(a, 'OutputMidiNumber')}},`);
  }
  lines.push('\t}},');
}
lines.push('}');
lines.push('');
lines.push('// tuningPresets is Tuning.getPresetsFor(n); the first entry of each list is the default tuning.');
lines.push('var tuningPresets = map[int][]tuningPreset{');
for (const n of [4, 5, 6, 7]) {
  lines.push(`\t${n}: {`);
  for (const t of m.Tuning.getPresetsFor(n)) {
    lines.push(`\t\t{${JSON.stringify(t.name)}, []int{${t.tunings.join(', ')}}, ${t.isStandard}},`);
  }
  lines.push('\t},');
}
lines.push('}');
lines.push('');
const style = files.get('Content/BinaryStylesheet');
lines.push('// binaryStylesheet is BinaryStylesheet.writeForScore for the default stylesheet.');
lines.push('var binaryStylesheet = []byte{');
for (let i = 0; i < style.length; i += 16) {
  lines.push('\t' + Array.from(style.subarray(i, i + 16)).map((b) => `0x${b.toString(16).padStart(2, '0')},`).join(' '));
}
lines.push('}');
fs.writeFileSync(process.argv[2], lines.join('\n') + '\n');
